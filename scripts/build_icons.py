def build(archive: bytes) -> dict[str, bytes]:
    if base64.b64encode(hashlib.sha512(archive).digest()).decode() != INTEGRITY:
        raise ValueError("Lucide package integrity does not match the pinned release")
    symbols = []
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as package:
        for name in ICONS:
            svg = ET.fromstring(package.extractfile(f"package/icons/{name}.svg").read())
            symbol = ET.Element("symbol", id=name, viewBox=svg.attrib["viewBox"])
            for child in svg:
                for node in child.iter():
                    node.tag = node.tag.removeprefix("{http://www.w3.org/2000/svg}")
                    node.tail = None
                symbol.append(child)
            symbols.append(ET.tostring(symbol, encoding="unicode"))
        license_text = package.extractfile("package/LICENSE").read().decode("utf-8")
    sprite = (f'<!-- lucide-static {VERSION}; generated by scripts/build_icons.py; see LICENSE. -->\n'
              '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n")
    return {"sprite.svg": sprite.encode(), "LICENSE": license_text.replace("\r\n", "\n").encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without changing them")
    args = parser.parse_args()
    cache = ROOT / ".cache" / "icons" / f"lucide-static-{VERSION}.tgz"
    if not cache.is_file():
        url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz"
        with urllib.request.urlopen(url, timeout=60) as response:
            archive = response.read()
        # Verify before retaining the download.
        outputs = build(archive)
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(archive)
    else:
        outputs = build(cache.read_bytes())
    destination = ROOT / "static" / "vendor" / "lucide"
    for name, data in outputs.items():
        path = destination / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f"Outdated: {path.relative_to(ROOT)}; run scripts/build_icons.py")
        else:
            destination.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"Lucide {VERSION}: {len(ICONS)} icons, {len(outputs['sprite.svg']):,} bytes; "
          + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
